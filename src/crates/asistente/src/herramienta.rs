//! A tool as the agent knows it - what it is called, what it does, what it
//! takes and what kind of effect it has - and what running one gives back,
//! in one shape whichever tool it was.

use serde_json::{Value, json};

/// What a tool does to the world, which decides whether the person is
/// asked first. The policy lives here, in the harness: the prompt only
/// explains it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Clase {
    /// Only reads.
    Lectura,
    /// Edits the project; one Ctrl+Z takes the turn back.
    Edicion,
    /// Edits that are hard to see coming: many clips gone, the frame of
    /// the whole project changed.
    Destructiva,
    /// Costs money: an image or a video generated by a paid AI.
    Gasto,
    /// Writes outside the project, or brings a file into it.
    Archivo,
}

impl Clase {
    /// Whether a call of this kind waits for the person's yes.
    pub fn pide_aprobacion(self) -> bool {
        matches!(self, Clase::Destructiva | Clase::Gasto | Clase::Archivo)
    }

    /// Whether it changes nothing.
    pub fn solo_lee(self) -> bool {
        self == Clase::Lectura
    }
}

/// The family every agent sees from the first step.
pub const NUCLEO: &str = "nucleo";

/// A tool the AI may call.
#[derive(Clone, Debug, PartialEq)]
pub struct Herramienta {
    /// Its name, as the AI calls it.
    pub nombre: String,
    /// What it does, for the AI.
    pub descripcion: String,
    /// Its arguments, as a JSON Schema.
    pub esquema: Value,
    /// What it does to the world.
    pub clase: Clase,
    /// The family it is offered with; [`NUCLEO`] is always offered, the
    /// rest once the AI asks for them with `herramientas_buscar`.
    pub familia: String,
    /// Calling it twice is calling it once: safe to repeat after a failure.
    pub idempotente: bool,
}

impl Herramienta {
    /// A tool; one that reads is idempotent, any other is not until
    /// [`Herramienta::idempotente`] says so.
    pub fn nueva(nombre: &str, descripcion: &str, esquema: Value, clase: Clase, familia: &str) -> Self {
        Self {
            nombre: nombre.to_owned(),
            descripcion: descripcion.to_owned(),
            esquema,
            clase,
            familia: familia.to_owned(),
            idempotente: clase.solo_lee(),
        }
    }

    /// The same tool, safe to repeat.
    pub fn idempotente(mut self) -> Self {
        self.idempotente = true;
        self
    }
}

/// Why a tool gave nothing useful.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tipo {
    /// It failed; the AI should read why and correct itself.
    Error,
    /// It was not run: a guard stopped it.
    Bloqueado,
    /// It was not run: the person said no.
    Rechazado,
    /// It was not run: the person pressed Stop.
    Cancelado,
    /// It ran and found nothing.
    Vacio,
    /// It did part of what was asked.
    Parcial,
}

impl Tipo {
    fn nombre(self) -> &'static str {
        match self {
            Tipo::Error => "error",
            Tipo::Bloqueado => "bloqueado",
            Tipo::Rechazado => "rechazado",
            Tipo::Cancelado => "cancelado",
            Tipo::Vacio => "vacio",
            Tipo::Parcial => "parcial",
        }
    }
}

/// A picture a tool shows the AI: a frame of the timeline.
#[derive(Clone, Debug, PartialEq)]
pub struct Imagen {
    /// "image/jpeg", "image/png".
    pub mime: String,
    /// The encoded picture.
    pub datos: Vec<u8>,
    /// What it is, in a line, kept when the picture itself is dropped
    /// from the context.
    pub nota: String,
}

/// What running a tool gave.
#[derive(Clone, Debug, PartialEq)]
pub struct Salida {
    /// What it gave, or why it failed.
    pub valor: Value,
    /// Why it gave nothing useful; None when it did what was asked.
    pub fallo: Option<Tipo>,
    /// A picture for the AI to look at.
    pub imagen: Option<Imagen>,
    /// How to get it right next time, when it failed.
    pub sugerencia: Option<String>,
}

impl Salida {
    /// It did what was asked.
    pub fn bien(valor: Value) -> Self {
        Self {
            valor,
            fallo: None,
            imagen: None,
            sugerencia: None,
        }
    }

    /// It failed, and says why.
    pub fn mal(tipo: Tipo, motivo: impl Into<String>) -> Self {
        Self {
            valor: json!(motivo.into()),
            fallo: Some(tipo),
            imagen: None,
            sugerencia: None,
        }
    }

    /// With a hint on how to get it right.
    pub fn con_sugerencia(mut self, sugerencia: impl Into<String>) -> Self {
        self.sugerencia = Some(sugerencia.into());
        self
    }

    /// With a picture for the AI.
    pub fn con_imagen(mut self, imagen: Imagen) -> Self {
        self.imagen = Some(imagen);
        self
    }

    /// Whether it did what was asked.
    pub fn ok(&self) -> bool {
        self.fallo.is_none()
    }

    /// The result as the AI reads it: `{ok, datos}` or `{ok: false,
    /// error, tipo, sugerencia?}`.
    pub fn para_la_ia(&self) -> Value {
        let mut valor = match self.fallo {
            None => json!({"ok": true, "datos": self.valor}),
            Some(tipo) => json!({"ok": false, "error": self.valor, "tipo": tipo.nombre()}),
        };
        if let Some(sugerencia) = &self.sugerencia {
            valor["sugerencia"] = json!(sugerencia);
        }
        valor
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_what_cannot_be_undone_in_place_asks_first() {
        assert!(!Clase::Lectura.pide_aprobacion());
        assert!(!Clase::Edicion.pide_aprobacion());
        assert!(Clase::Destructiva.pide_aprobacion());
        assert!(Clase::Gasto.pide_aprobacion());
        assert!(Clase::Archivo.pide_aprobacion());
    }

    #[test]
    fn a_result_reads_the_same_whichever_tool_gave_it() {
        assert_eq!(Salida::bien(json!(3)).para_la_ia(), json!({"ok": true, "datos": 3}));
        assert_eq!(
            Salida::mal(Tipo::Rechazado, "la persona dijo que no").para_la_ia(),
            json!({"ok": false, "error": "la persona dijo que no", "tipo": "rechazado"})
        );
        assert_eq!(
            Salida::mal(Tipo::Error, "no existe c7").con_sugerencia("lee timeline_read").para_la_ia()["sugerencia"],
            "lee timeline_read"
        );
    }
}
